import { badRequest, guard, json, readJson } from '@/lib/api';
import { getDb, num } from '@/lib/db';
import { checkAchievements } from '@/lib/achievements';
import { recordWorkout, refreshChallengeTotals, sanitizeDayKey } from '@/lib/stats';
import { buildLeaderboard, notifyFriendsOfOvertake } from '@/lib/social';
import { validateIsoDate, validateNumber } from '@/lib/validation';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * SAVING A WORKOUT
 * ================
 * The browser counts the reps (the camera never leaves the device) and posts
 * the finished session here.
 *
 * Two protections matter:
 *
 *  1. IDEMPOTENCY. The session id is generated by the browser before the
 *     workout starts and is the primary key. If the phone loses signal and
 *     retries the upload three times, the extra attempts are ignored - your
 *     score can only ever increase once per session.
 *
 *  2. AUDIT. The server does not blindly trust the number. `recordWorkout`
 *     compares the rep count against the session's real duration and flags
 *     anything a human body could not have done. Flagged sessions are stored
 *     (so nothing is silently lost) but do not count towards totals.
 */
export async function POST(request: Request): Promise<Response> {
  return guard(async () => {
    const { user, response } = await requireUser();
    if (!user) return response;

    const body = await readJson<{
      id?: string;
      startedAt?: string;
      endedAt?: string;
      reps?: number;
      invalidReps?: number;
      validationScore?: number;
      device?: string;
      dayKey?: string;
    }>(request);
    if (!body) return badRequest('We could not read that workout.');

    const sessionId = String(body.id ?? '').trim();
    // Accept only a UUID-shaped id so a crafted value cannot overwrite another row.
    if (!/^[0-9a-fA-F-]{20,40}$/.test(sessionId)) {
      return badRequest('That workout id is not valid.');
    }

    const startedAt = validateIsoDate(body.startedAt);
    const endedAt = validateIsoDate(body.endedAt);
    if (!startedAt || !endedAt) return badRequest('That workout has invalid timestamps.');
    if (new Date(endedAt).getTime() < new Date(startedAt).getTime()) {
      return badRequest('That workout ends before it starts.');
    }

    const reps = validateNumber(body.reps, { min: 0, max: 5000, fallback: 0 });
    const invalidReps = validateNumber(body.invalidReps, { min: 0, max: 5000, fallback: 0 });
    const validationScore = Math.max(0, Math.min(1, Number(body.validationScore ?? 1) || 0));

    // A session may not be filed more than 2 days away from the server date.
    const dayKey = sanitizeDayKey(body.dayKey);
    const device = String(body.device ?? '').slice(0, 120) || null;

    const result = await recordWorkout({
      sessionId,
      userId: user.id,
      startedAt,
      endedAt,
      dayKey,
      reps,
      invalidReps,
      validationScore,
      device,
    });

    let newAchievements: Array<{ code: string; name: string; description: string; icon: string }> = [];

    if (!result.duplicate) {
      await refreshChallengeTotals(user.id, dayKey);
      try {
        const unlocked = await checkAchievements(user.id, dayKey);
        newAchievements = unlocked.map((a) => ({
          code: a.code, name: a.name, description: a.description, icon: a.icon,
        }));
      } catch (error) {
        console.error('[workouts] achievements', error);
      }
      try {
        await notifyFriendsOfOvertake(user.id, dayKey);
      } catch (error) {
        console.error('[workouts] notify', error);
      }
    }

    const leaderboard = await buildLeaderboard(user.id, dayKey, 'today');

    return json({
      duplicate: result.duplicate,
      accepted: result.accepted,
      flagged: result.flagged,
      flaggedReason: result.flaggedReason,
      stats: result.stats,
      newAchievements,
      leaderboard,
    });
  });
}

/** Recent sessions, newest first - shown on the profile and dashboard. */
export async function GET(request: Request): Promise<Response> {
  return guard(async () => {
    const { user, response } = await requireUser();
    if (!user) return response;

    const url = new URL(request.url);
    const limit = Math.min(100, Math.max(1, Number(url.searchParams.get('limit') ?? 25) || 25));

    const db = await getDb();
    const sessions = await db.all<{
      id: string;
      started_at: string;
      ended_at: string;
      pushup_count: number;
      invalid_count: number;
      validation_score: number;
      duration_ms: number;
      flagged: number | boolean;
    }>(
      `SELECT id, started_at, ended_at, pushup_count, invalid_count, validation_score, duration_ms, flagged
         FROM workout_sessions
        WHERE user_id = ?
        ORDER BY started_at DESC
        LIMIT ?`,
      [user.id, limit],
    );

    return json({
      sessions: sessions.map((s) => ({
        id: s.id,
        startedAt: s.started_at,
        endedAt: s.ended_at,
        pushups: num(s.pushup_count),
        invalidReps: num(s.invalid_count),
        validationScore: Number(s.validation_score ?? 1),
        durationMs: num(s.duration_ms),
        flagged: num(s.flagged) === 1,
      })),
    });
  });
}
